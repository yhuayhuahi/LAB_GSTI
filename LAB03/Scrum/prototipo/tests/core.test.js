const assert=require('node:assert/strict');
const C=require('../core.js');
let s=C.emptyState();
s=C.registerProduct(s,{code:'A1',name:'Arroz',category:'Alimentos',price:'4.5',min:'2',stock:'10'},null,'2026-10-17T14:00:00.000Z');
assert.equal(s.products.length,1);
assert.equal(s.products[0].stock,10);
assert.throws(()=>C.registerProduct(s,{code:'a1',name:'Duplicado',category:'A',price:'2',min:'1',stock:'1'}),/existe/);
assert.equal(C.stockStatus(s.products[0]),'Disponible');
const id=s.products[0].id;
s=C.moveStock(s,id,'Entrada',5,{text:'',deltaSign:'1'});
assert.equal(s.products[0].stock,15);
assert.throws(()=>C.moveStock(s,id,'Ajuste',1,{text:'',deltaSign:'-1'}),/motivo/);
s=C.moveStock(s,id,'Ajuste',2,{text:'Merma',deltaSign:'-1'});
assert.equal(s.products[0].stock,13);
assert.throws(()=>C.moveStock(s,id,'Ajuste',100,{text:'Merma',deltaSign:'-1'}),/negativo/);
s=C.registerSale(s,[{productId:id,quantity:3}],'2026-10-17T16:00:00.000Z');
assert.equal(s.products[0].stock,10);
assert.equal(s.sales[0].total,13.5);
assert.equal(s.sales[0].lines[0].quantity,3);
assert.equal(s.movements[0].type,'Venta');
assert.throws(()=>C.registerSale(s,[{productId:id,quantity:11}]),/insuficiente/);
assert.equal(s.products[0].stock,10);
assert.equal(C.totals(s).revenue,13.5);
assert.equal(C.dateInRange('2026-10-17T16:00:00.000Z','2026-10-17','2026-10-17'),true);
console.log('OK: 15 comprobaciones automatizadas de lógica de inventario');
